    t = wikitext(os.path.join(folder, "p_Enkephalin.json"))
    table = []
    for lv, xp, cap in re.findall(r"\|\s*(\d+)\s*\|\|\s*(\d*)\s*\|\|\s*(\d+)", t):
        table.append([int(lv), int(xp) if xp else 0, int(cap)])
    return {"levels": table, "regen_minutes": 6, "module_cost": 20, "box": 60, "refresh_lunacy": 26, "refreshes": 10}


