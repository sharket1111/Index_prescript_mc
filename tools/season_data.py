def projection(folder):
    t = open(os.path.join(folder, "Mirror_of_Sisyphe.txt"), encoding="utf-8").read()
    start = t.find("=== Achievements List ===")
    block = t[start:t.find("=== Rewards ===", start)]
    out, cat = [], None
    for line in block.split("\n"):
        m = re.match(r"\|-\|\s*([^=]+?)\s*=", line)
        if m:
            cat = m.group(1)
            continue
        m = re.match(r"\|(.+?)\|\|\{\{Icons\|MD8 Projection Rate\}\}\s*(\d+)", line)
        if not m or cat not in CAT_KO:
            continue
        en = re.sub(r"<br\s*/?>", " ", m.group(1)).strip()
        cond, ko = condition(en)
        out.append({"id": "a%03d" % len(out), "category": CAT_KO[cat], "text_en": en, "text": ko or en, "rate": int(m.group(2)), "when": cond})
    rewards = []
    r0 = t.find("=== Rewards ===")
    for lv, body in re.findall(r"\n\|(\d+)\|\|(.+)", t[r0:t.find("==Mounting Trials==", r0)]):
        body = re.sub(r"\{\{Icons\|[^}]*\}\}", "", body).strip()
        m = re.match(r"(.+?) x(\d+)$", body)
        if m:
            name, n = m.group(1).strip(), int(m.group(2))
            rewards.append({"level": int(lv), "items": [[ITEM[name], n]]})
        elif "Banner" in body:
            rewards.append({"level": int(lv), "items": [["banner:" + body, 1]]})
        else:
            rewards.append({"level": int(lv), "items": [["deco:" + body, 1]]})
    runs = {"normal_floor": 5, "hard_floor": 10, "deep": {str(f): r for f, r in
                                                       [(6, 15), (7, 15), (8, 20), (9, 20), (10, 30), (11, 40), (12, 50), (13, 80), (14, 125), (15, 200)]},
            "adversity": 15, "weekly_cap": 1000, "per_level": 100, "levels": 100}
    return {"dungeon": "Mirror of Sisyphe", "achievements": out, "completionist": ["banner:Season 8: Mirror of Sisyphe Special Achievement Banner", 1],
            "rewards": rewards, "runs": runs}


